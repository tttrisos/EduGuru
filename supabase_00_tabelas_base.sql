-- ============================================================
-- EduGuru — Script 00: criação das tabelas base
-- (disciplinas, perguntas e materiais)
--
-- Por quê: na Fase 1 essas três tabelas foram criadas pelo painel do
-- Supabase, sem script. Os SQLs seguintes só as ALTERAM. Este arquivo
-- registra a criação para que o banco possa ser montado do zero, na
-- ordem: 00 → supabase_setup_auth_logs.sql → atualizacao_2 … _12.
--
-- No banco que já existe, rodar este script não muda nada: o
-- "create table if not exists" pula as tabelas que já estão lá.
--
-- Aqui fica só o formato ORIGINAL (Fase 1). As colunas que vieram
-- depois (arquivo, enviado_por, disciplina_id, alternativas...) são
-- acrescentadas pelas atualizações, cada uma com a sua explicação.
-- ============================================================

create table if not exists public.disciplinas (
  id bigint generated by default as identity primary key,
  nome text not null,
  curso text not null            -- 'SI' | 'ADS' | 'ES'
);

create table if not exists public.perguntas (
  id bigint generated by default as identity primary key,
  enunciado text not null,
  disciplina text,               -- Fase 1: texto (era o curso). Trocado por FK na atualização 11.
  nivel text not null default 'Fácil'
);

create table if not exists public.materiais (
  id bigint generated by default as identity primary key,
  titulo text not null,
  link text                      -- Fase 1 era obrigatório; na atualização 2 virou opcional (arquivo).
);
